/*
小明过生日的时候，爸爸送给他一副乌龟棋当作礼物。
乌龟棋的棋盘是一行 N 个格子，每个格子上一个分数（非负整数）。棋盘第 1 格是唯一的起点，第 N 格是终点，游戏要求玩家控制一个乌龟棋子从起点出发走到终点。
乌龟棋中 M 张爬行卡片，分成 4 种不同的类型（M 张卡片中不一定包含所有 4 种类型的卡片，见样例），每种类型的卡片上分别标有 1,2,3,4 四个数字之一，表示使用这种卡片后，乌龟棋子将向前爬行相应的格子数。
游戏中，玩家每次需要从所有的爬行卡片中选择一张之前没有使用过的爬行卡片，控制乌龟棋子前进相应的格子数，每张卡片只能使用一次。
游戏中，乌龟棋子自动获得起点格子的分数，并且在后续的爬行中每到达一个格子，就得到该格子相应的分数。玩家最终游戏得分就是乌龟棋子从起点到终点过程中到过的所有格子的分数总和。
很明显，用不同的爬行卡片使用顺序会使得最终游戏的得分不同，小明想要找到一种卡片使用顺序使得最终游戏得分最多。
现在，告诉你棋盘上每个格子的分数和所有的爬行卡片，你能告诉小明，他最多能得到多少分吗？
输入格式
每行中两个数之间用一个空格隔开。
第 1 行 2 个正整数 N,M，分别表示棋盘格子数和爬行卡片数。
第 2 行 N 个非负整数，a_1,a_2,…,a_N其中a_i表示棋盘第 i 个格子上的分数。
第 3 行 M 个整数，b_1,b_2,…,b_M​，表示 M 张爬行卡片上的数字。
输入数据保证到达终点时刚好用光 M 张爬行卡片。
输出格式
一个整数，表示小明最多能得到的分数。
*/
#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;
int main(){
    int N,M,x,dp[41][41][41][41];
    cin>>N>>M;
    vector<int> a(N,0),b(5,0);
    for (int i=0;i<N;i++) cin>>a[i];
    for (int i=0;i<M;i++){
        cin>>x;
        b[x]++;
    }
    dp[0][0][0][0]=a[0];
    for (int i=0;i<=b[1];i++) {
        for (int j=0;j<=b[2];j++) {
            for (int k=0;k<=b[3];k++) {
                for (int l=0;l<=b[4];l++) {
                    if (i==0&&j==0&&k==0&&l==0) continue;
                    int pos=i+2*j+3*k+4*l,best=0;
                    if (i>0) best=max(best,dp[i-1][j][k][l]);
                    if (j>0) best=max(best,dp[i][j-1][k][l]);
                    if (k>0) best=max(best,dp[i][j][k-1][l]);
                    if (l>0) best=max(best,dp[i][j][k][l-1]);
                    dp[i][j][k][l]=best+a[pos];
                }
            }
        }
    }
    cout<<dp[b[1]][b[2]][b[3]][b[4]];
    return 0;
}